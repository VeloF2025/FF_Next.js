#!/usr/bin/env node

/**
 * Embed Manual Content Script
 * 
 * Reads the actual manual markdown file and embeds it into the manual-content.ts file
 */

const fs = require('fs');
const path = require('path');

const MANUAL_SOURCE_PATH = path.join(__dirname, '..', 'docs', 'user-manuals', 'source', 'fibreflow-complete.md');
const MANUAL_TARGET_PATH = path.join(__dirname, '..', 'src', 'modules', 'help-center', 'data', 'manual-content.ts');

function escapeStringForJS(str) {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\${/g, '\\${');
}

function generateManualContent() {
  try {
    console.log('📖 Reading manual content...');
    
    // Check if manual file exists
    if (!fs.existsSync(MANUAL_SOURCE_PATH)) {
      console.error('❌ Manual file not found at:', MANUAL_SOURCE_PATH);
      process.exit(1);
    }
    
    // Read the manual content
    const manualContent = fs.readFileSync(MANUAL_SOURCE_PATH, 'utf-8');
    console.log(`✅ Manual content read (${manualContent.length} characters)`);
    
    // Generate the TypeScript file content
    const fileContent = `/**
 * FibreFlow User Manual Content
 * 
 * Auto-generated from docs/user-manuals/source/fibreflow-complete.md
 * Last updated: ${new Date().toISOString()}
 * 
 * DO NOT EDIT THIS FILE MANUALLY - run \`npm run embed-manual\` to regenerate
 */

const MANUAL_CONTENT = \`${escapeStringForJS(manualContent)}\`;

export interface ManualSection {
  id: string;
  title: string;
  content: string;
  subsections: ManualSubsection[];
}

export interface ManualSubsection {
  id: string;
  title: string;
  content: string;
}

export interface SearchResult {
  sectionId: string;
  sectionTitle: string;
  subsectionId?: string;
  subsectionTitle?: string;
  content: string;
  matchedText: string;
}

/**
 * Parse the manual content into sections
 */
export function parseManualSections(): ManualSection[] {
  if (!MANUAL_CONTENT) return [];
  
  const lines = MANUAL_CONTENT.split('\\n');
  const sections: ManualSection[] = [];
  
  let currentSection: ManualSection | null = null;
  let currentSubsection: ManualSubsection | null = null;
  let contentBuffer: string[] = [];
  
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    
    // Main section (## N. Title)
    if (line.match(/^## \\d+\\./)) {
      // Save previous content
      if (currentSubsection) {
        currentSubsection.content = contentBuffer.join('\\n').trim();
      } else if (currentSection) {
        currentSection.content = contentBuffer.join('\\n').trim();
      }
      
      // Save previous section
      if (currentSection) {
        if (currentSubsection) {
          currentSection.subsections.push(currentSubsection);
        }
        sections.push(currentSection);
      }
      
      // Start new section
      const title = line.replace(/^## \\d+\\.\\s*/, '');
      currentSection = {
        id: slugify(title),
        title,
        content: '',
        subsections: []
      };
      currentSubsection = null;
      contentBuffer = [];
    }
    // Subsection (### Title)
    else if (line.match(/^###\\s+/)) {
      // Save previous subsection content
      if (currentSubsection) {
        currentSubsection.content = contentBuffer.join('\\n').trim();
        if (currentSection) {
          currentSection.subsections.push(currentSubsection);
        }
      } else if (currentSection) {
        // Save section content before first subsection
        currentSection.content = contentBuffer.join('\\n').trim();
      }
      
      // Start new subsection
      const title = line.replace(/^###\\s*/, '');
      currentSubsection = {
        id: slugify(title),
        title,
        content: ''
      };
      contentBuffer = [];
    }
    // Other section header (## without number) - skip these for now
    else if (line.match(/^##\\s+/) && !line.match(/^## \\d+\\./)) {
      // Skip non-numbered sections like "Table of Contents"
      continue;
    }
    // Regular content
    else {
      contentBuffer.push(line);
    }
  }
  
  // Save the last section/subsection
  if (currentSubsection) {
    currentSubsection.content = contentBuffer.join('\\n').trim();
    if (currentSection) {
      currentSection.subsections.push(currentSubsection);
    }
  } else if (currentSection) {
    currentSection.content = contentBuffer.join('\\n').trim();
  }
  
  if (currentSection) {
    sections.push(currentSection);
  }
  
  return sections.filter(section => section.title.length > 0);
}

/**
 * Search through the manual content
 */
export function searchManual(query: string, sections: ManualSection[]): SearchResult[] {
  if (!query.trim()) return [];
  
  const results: SearchResult[] = [];
  const searchTerms = query.toLowerCase().split(' ');
  
  sections.forEach(section => {
    // Search in section content
    const sectionContent = section.content.toLowerCase();
    const matchesSection = searchTerms.every(term => sectionContent.includes(term));
    
    if (matchesSection && section.content.trim()) {
      const matchIndex = sectionContent.indexOf(searchTerms[0]);
      const context = extractContext(section.content, matchIndex, 200);
      
      results.push({
        sectionId: section.id,
        sectionTitle: section.title,
        content: section.content,
        matchedText: context
      });
    }
    
    // Search in subsections
    section.subsections.forEach(subsection => {
      const subsectionContent = subsection.content.toLowerCase();
      const matchesSubsection = searchTerms.every(term => subsectionContent.includes(term));
      
      if (matchesSubsection && subsection.content.trim()) {
        const matchIndex = subsectionContent.indexOf(searchTerms[0]);
        const context = extractContext(subsection.content, matchIndex, 200);
        
        results.push({
          sectionId: section.id,
          sectionTitle: section.title,
          subsectionId: subsection.id,
          subsectionTitle: subsection.title,
          content: subsection.content,
          matchedText: context
        });
      }
    });
  });
  
  return results;
}

/**
 * Create URL-friendly slug from text
 */
function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\\w\\s-]/g, '')
    .replace(/[\\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Extract context around a match
 */
function extractContext(content: string, matchIndex: number, contextLength: number): string {
  const start = Math.max(0, matchIndex - contextLength / 2);
  const end = Math.min(content.length, matchIndex + contextLength / 2);
  
  let context = content.substring(start, end);
  
  // Trim to word boundaries
  if (start > 0) {
    const firstSpace = context.indexOf(' ');
    if (firstSpace > 0) {
      context = '...' + context.substring(firstSpace);
    }
  }
  
  if (end < content.length) {
    const lastSpace = context.lastIndexOf(' ');
    if (lastSpace > 0 && lastSpace < context.length - 10) {
      context = context.substring(0, lastSpace) + '...';
    }
  }
  
  return context;
}

export default MANUAL_CONTENT;
`;

    // Write the generated content
    console.log('💾 Writing manual content to TypeScript file...');
    fs.writeFileSync(MANUAL_TARGET_PATH, fileContent);
    console.log('✅ Manual content embedded successfully!');
    console.log(`📝 File written to: ${MANUAL_TARGET_PATH}`);
    
  } catch (error) {
    console.error('❌ Error embedding manual content:', error.message);
    process.exit(1);
  }
}

// Run the script
if (require.main === module) {
  generateManualContent();
}

module.exports = { generateManualContent };